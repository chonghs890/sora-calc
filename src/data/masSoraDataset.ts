/**
 * Computes Compounded SORA following the exact MAS Compounding Formula:
 * Compounded SORA = [ product_{i=1}^{d_0} (1 + (SORA_i * n_i) / 36500) - 1 ] * (36500 / d)
 *
 * @param rates Array of daily rates with their day weights
 * @param totalDays Total calendar days in calculation period
 * @returns Compounded annual percentage rounded to 4 decimal places
 */
export function calculateMASCompoundedSORA(
  rates: { sora: number; dayWeight: number }[],
  totalDays: number
): number {
  if (rates.length === 0 || totalDays <= 0) return 0;

  let product = 1.0;
  for (const item of rates) {
    // SORA is entered in %, so divide by 100 * 365 = 36500
    const dailyFactor = 1.0 + (item.sora * item.dayWeight) / 36500.0;
    product *= dailyFactor;
  }

  const compoundedRate = (product - 1.0) * (36500.0 / totalDays);
  return Number(compoundedRate.toFixed(4));
}
